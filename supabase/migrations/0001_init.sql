exception when duplicate_object then null; end $$;

-- ---------------------------------------------------------------------------
-- Projects
-- ---------------------------------------------------------------------------

create table if not exists public.projects (
  id                  uuid primary key default gen_random_uuid(),
  user_id             uuid not null references auth.users (id) on delete cascade,
  name                text not null check (char_length(name) between 1 and 80),

  -- The hostname the customer points at us.
  domain              text not null check (domain = lower(domain) and domain ~ '^[a-z0-9.-]+\.[a-z]{2,}$'),
  -- Where we forward to.
  origin_url          text not null check (origin_url ~ '^https?://'),

  status              project_status not null default 'pending',

  -- 32 random bytes, base64url. Generated by the database so it is never
  -- supplied, seen, or chosen by the client. Never leaves the server except to
  -- the edge worker via edge_config().
  tpm_secret          text not null
                        default translate(encode(extensions.gen_random_bytes(32), 'base64'), '+/', '-_'),

  -- DNS ownership proof: TXT _foundershield.<domain> = this value.
  verification_token  text not null default encode(extensions.gen_random_bytes(16), 'hex'),
  dns_verified_at     timestamptz,
  proxy_verified_at   timestamptz,

  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),

  unique (domain)
);

create index if not exists projects_user_id_idx on public.projects (user_id);

