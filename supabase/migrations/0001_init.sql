create table if not exists public.request_events (
  id               bigserial primary key,
  project_id       uuid not null references public.projects (id) on delete cascade,
  occurred_at      timestamptz not null,
  recorded_at      timestamptz not null default clock_timestamp(),

  -- Observation
  ip               inet,
  ip_hash          text not null,
  method           text not null,
  host             text not null,
  path             text not null,
  query            text,
  user_agent       text not null default '',
  referer          text,
  country          text,
  asn              integer,
  as_organisation  text,
  tls_version      text,
  edge_location    text,
  request_id       text,

  -- Interpretation
  action           decision_action not null,
  enforced         boolean not null default true,
  primary_layer    decision_layer,
  reasons          jsonb not null default '[]'::jsonb,
  bot_score        smallint not null default 0,
  session_id       text,
  client_signals   jsonb,

  -- Service metrics: the server-burden measure.
  response_status  integer not null,
  decision_ms      integer not null default 0,
  origin_ms        integer,
  response_bytes   integer,

  -- Tamper-evidence, computed by trigger from immutable columns only.
  row_hash         text
);

create index if not exists request_events_project_time_idx
  on public.request_events (project_id, occurred_at desc);
create index if not exists request_events_project_action_idx
  on public.request_events (project_id, action, occurred_at desc);
create index if not exists request_events_project_ip_idx
  on public.request_events (project_id, ip_hash, occurred_at desc);

-- Canonical serialisation, then hash. Column order is fixed here on purpose:
-- changing it changes every future hash, so it must be a deliberate migration.
--
-- This is a pure function of a row's *current* contents, which is what makes
-- tamper detection work. Verification re-derives it from live data rather than
-- trusting the stored `row_hash`; if it only re-hashed the stored hashes, an
-- UPDATE to any observation column would go unnoticed, because the trigger
-- fires on INSERT only.
create or replace function public.event_row_hash(e public.request_events)
returns text
language sql
immutable
as $$
  select encode(
    sha256(convert_to(
      concat_ws('|',
        e.project_id::text,
        to_char(e.occurred_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
        coalesce(host(e.ip), ''),
        e.ip_hash,
        e.method,
        e.host,
        e.path,
        coalesce(e.query, ''),
        e.user_agent,
        coalesce(e.referer, ''),
        coalesce(e.country, ''),
        coalesce(e.asn::text, ''),
        coalesce(e.as_organisation, ''),
        coalesce(e.edge_location, ''),
        coalesce(e.request_id, ''),
        e.action::text,
        e.enforced::text,
        coalesce(e.primary_layer::text, ''),
        e.reasons::text,
        e.bot_score::text,
        e.response_status::text
      ), 'UTF8')),
    'hex');
$$;

create or replace function public.compute_event_hash()
returns trigger
language plpgsql
as $$
begin
  new.row_hash := public.event_row_hash(new);
  return new;
end;
$$;

drop trigger if exists request_events_hash on public.request_events;
create trigger request_events_hash
  before insert on public.request_events
  for each row execute function public.compute_event_hash();

-- ---------------------------------------------------------------------------
-- Evidence seals
--
-- A seal fixes the content of a closed range of events. Producing one is cheap
-- and can be scheduled; verifying one later detects any alteration, insertion
-- or deletion inside the sealed range.
-- ---------------------------------------------------------------------------

create table if not exists public.evidence_seals (
  id           uuid primary key default gen_random_uuid(),
  project_id   uuid not null references public.projects (id) on delete cascade,
  from_event   bigint not null,
  to_event     bigint not null,
  event_count  integer not null,
  digest       text not null,
  previous_id  uuid references public.evidence_seals (id),
  sealed_at    timestamptz not null default now(),
  check (to_event >= from_event)
);

create index if not exists evidence_seals_project_idx
  on public.evidence_seals (project_id, sealed_at desc);

create or replace function public.seal_evidence(p_project_id uuid)
returns public.evidence_seals
language plpgsql
security invoker
as $$
declare
  v_previous public.evidence_seals;
  v_start    bigint;
  v_from     bigint;
  v_to       bigint;
  v_count    integer;
  v_digest   text;
  v_seal     public.evidence_seals;
begin
  -- RLS on projects governs whether the caller may seal this project at all.
  if not exists (select 1 from public.projects p where p.id = p_project_id) then
    raise exception 'project not found';
  end if;

  select * into v_previous
  from public.evidence_seals
  where project_id = p_project_id
  order by to_event desc
  limit 1;

  v_start := coalesce(v_previous.to_event + 1, 0);

  select min(id), max(id), count(*)
    into v_from, v_to, v_count
  from public.request_events
  where project_id = p_project_id
    and id >= v_start;

  if v_count is null or v_count = 0 then
    raise exception 'no unsealed events for this project';
  end if;

  -- Chain into the previous seal so seals cannot be reordered or dropped.
  select encode(sha256(convert_to(
           coalesce(v_previous.digest, '') || string_agg(public.event_row_hash(e), '' order by e.id), 'UTF8')), 'hex')
    into v_digest
  from public.request_events e
  where e.project_id = p_project_id and e.id between v_from and v_to;

  insert into public.evidence_seals (project_id, from_event, to_event, event_count, digest, previous_id)
  values (p_project_id, v_from, v_to, v_count, v_digest, v_previous.id)
  returning * into v_seal;

  return v_seal;
end;
$$;

create or replace function public.verify_evidence_seal(p_seal_id uuid)
returns jsonb
language plpgsql
security invoker
as $$
declare
  v_seal     public.evidence_seals;
  v_previous public.evidence_seals;
  v_actual   text;
  v_count    integer;
  v_altered  integer;
begin
  select * into v_seal from public.evidence_seals where id = p_seal_id;
  if v_seal.id is null then
    raise exception 'seal not found';
  end if;

  select * into v_previous from public.evidence_seals where id = v_seal.previous_id;

  -- Recomputed from the rows as they stand right now. `v_altered` additionally
  -- reports rows whose stored hash no longer matches their own contents, which
  -- localises an edit instead of only flagging the range as broken.
  select encode(sha256(convert_to(
           coalesce(v_previous.digest, '') || string_agg(public.event_row_hash(e), '' order by e.id), 'UTF8')), 'hex'),
         count(*),
         count(*) filter (where e.row_hash is distinct from public.event_row_hash(e))
    into v_actual, v_count, v_altered
  from public.request_events e
  where e.project_id = v_seal.project_id and e.id between v_seal.from_event and v_seal.to_event;

  return jsonb_build_object(
    'sealId', v_seal.id,
    'intact', v_actual is not distinct from v_seal.digest
              and v_count = v_seal.event_count
              and coalesce(v_altered, 0) = 0,
    'expectedDigest', v_seal.digest,
    'actualDigest', v_actual,
    'expectedCount', v_seal.event_count,
    'actualCount', v_count,
    'alteredRows', coalesce(v_altered, 0),
    'sealedAt', v_seal.sealed_at
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- Edge configuration lookup (called by the worker with the service role)
-- ---------------------------------------------------------------------------

create or replace function public.edge_config(p_domain text)
returns jsonb
language sql
security definer
set search_path = public
stable
as $$
  select jsonb_build_object(
    'projectId',   p.id,
    'domain',      p.domain,
    'originUrl',   p.origin_url,
    'status',      p.status,
    'tpmSecret',   p.tpm_secret,
    'mode',        coalesce(s.mode, 'standard'),
    'tpm',         coalesce(s.tpm, '{}'::jsonb),
    'rateLimit',   coalesce(s.rate_limit, '{}'::jsonb),
    'bots',        coalesce(s.bots, '{}'::jsonb),
    'authGate',    coalesce(s.auth_gate, '{}'::jsonb),
    'clickwrap',   coalesce(s.clickwrap, '{}'::jsonb),
    'logging',     coalesce(s.logging, '{}'::jsonb),
    'ipAllowlist', coalesce(s.ip_allowlist, '[]'::jsonb),
    'ipBlocklist', coalesce(s.ip_blocklist, '[]'::jsonb)
  )
  from public.projects p
  left join public.protection_settings s on s.project_id = p.id
  where p.domain = lower(p_domain)
  limit 1;
$$;

revoke all on function public.edge_config(text) from public, anon, authenticated;
grant execute on function public.edge_config(text) to service_role;

