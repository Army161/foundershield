-- ---------------------------------------------------------------------------
-- Column-level grants
--
-- RLS decides *which rows* a caller sees; these grants decide *which columns*
-- they may touch at all. Both are needed: a policy mistake alone must not be
-- enough to expose a project secret or let a customer mark their own domain
-- as verified.
--
-- A column-level REVOKE is a no-op while a table-level grant is held, so the
-- table-level privilege is dropped first and re-granted per column.
-- ---------------------------------------------------------------------------

-- Start from zero rather than trusting whatever ambient default privileges the
-- project happens to have. Supabase normally grants ALL on new public tables to
-- anon and authenticated, but that depends on ALTER DEFAULT PRIVILEGES having
-- been configured for whichever role runs this migration — which is not
-- guaranteed across projects, CLI versions, or a self-hosted deployment. For a
-- schema whose whole job is access control, ambient is not good enough.
revoke all on public.projects            from authenticated, anon;
revoke all on public.protection_settings from authenticated, anon;
revoke all on public.request_events      from authenticated, anon;
revoke all on public.evidence_seals      from authenticated, anon;

-- Projects. Note the omission of `tpm_secret` from every grant: it is readable
-- only by the service role, so a query selecting it fails rather than leaks.
grant select (
  id, user_id, name, domain, origin_url, status,
  verification_token, dns_verified_at, proxy_verified_at, created_at, updated_at
) on public.projects to authenticated;

-- `tpm_secret`, `status` and the verification timestamps are all server-set:
-- absent from both grants, so a customer cannot assert them about themselves.
grant insert (user_id, name, domain, origin_url) on public.projects to authenticated;
grant update (name, origin_url)                  on public.projects to authenticated;
grant delete                                     on public.projects to authenticated;

-- Protection settings are entirely customer-owned. The row itself is created by
-- the SECURITY DEFINER trigger, so no INSERT grant is needed.
grant select, update on public.protection_settings to authenticated;

-- Evidence is read-only to everyone except the edge worker's service role.
grant select on public.request_events to authenticated;

-- Seals may be created by the owner but never amended.
grant select, insert on public.evidence_seals to authenticated;

-- Functions are EXECUTE-to-PUBLIC by default, so state the intent explicitly
-- in both directions.
revoke all on function public.seal_evidence(uuid)                        from public, anon;
revoke all on function public.verify_evidence_seal(uuid)                 from public, anon;
revoke all on function public.project_event_stats(uuid, timestamptz)     from public, anon;
grant execute on function public.seal_evidence(uuid)                     to authenticated;
grant execute on function public.verify_evidence_seal(uuid)              to authenticated;
grant execute on function public.project_event_stats(uuid, timestamptz)  to authenticated;

-- `anon` is left with nothing at all: an unauthenticated caller has no
-- legitimate reason to touch any of this.

-- The service role is the trusted backend identity — the edge worker writing
-- evidence, and the dashboard recording a verification result. It is granted
-- explicitly for the same reason as everything above: relying on ambient
-- default privileges here fails *silently*, because a rejected evidence write
-- is logged and discarded rather than surfaced to anyone.
grant all on public.projects            to service_role;
grant all on public.protection_settings to service_role;
grant all on public.request_events      to service_role;
grant all on public.evidence_seals      to service_role;

-- request_events.id is a bigserial, so inserting also needs the sequence.
grant usage, select on all sequences in schema public to service_role;
