-- ===========================================================================
-- FounderShield — core schema
--
-- Design notes that matter:
--   * `request_events` is append-only by grant, not by convention. Owners can
--     read their evidence and nothing else; only the edge worker (service role)
--     writes. There is no UPDATE or DELETE grant for any human role.
--   * Every event carries a `row_hash` computed server-side at insert time from
--     the columns the client cannot influence. `evidence_seals` then chains
--     ranges of those hashes, so a later alteration is detectable without
--     paying for per-row chaining on the write path.
--   * `edge_config()` is the single read the proxy performs. It is SECURITY
--     DEFINER so the worker never needs table-level grants.
-- ===========================================================================

-- `gen_random_bytes` lives in pgcrypto; `gen_random_uuid` and `sha256` are core.
create extension if not exists pgcrypto with schema extensions;

