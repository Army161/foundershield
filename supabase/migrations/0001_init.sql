                 'enabled', false,
                 'authCookieName', 'session',
                 'loginPath', '/login',
                 'routes', jsonb_build_array()
               ),

  clickwrap    jsonb not null default jsonb_build_object(
                 'enabled', false, 'version', '1', 'tosUrl', '/terms', 'requiredPaths', jsonb_build_array()
               ),

  logging      jsonb not null default jsonb_build_object('sampleRate', 0.02, 'logAllowed', true),

  ip_allowlist jsonb not null default jsonb_build_array(),
  ip_blocklist jsonb not null default jsonb_build_array(),

  updated_at   timestamptz not null default now()
);

