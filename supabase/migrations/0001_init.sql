create or replace function public.project_event_stats(p_project_id uuid, p_since timestamptz)
returns jsonb
language sql
security invoker
stable
as $$
  with scoped as (
    select * from public.request_events
    where project_id = p_project_id and occurred_at >= p_since
  )
  select jsonb_build_object(
    'total',     (select count(*) from scoped),
    'blocked',   (select count(*) from scoped where action = 'block'),
    'challenged',(select count(*) from scoped where action = 'challenge'),
    'allowed',   (select count(*) from scoped where action = 'allow'),
    'byLayer',   (select coalesce(jsonb_object_agg(primary_layer, n), '{}'::jsonb)
                  from (select primary_layer, count(*) n from scoped
                        where primary_layer is not null group by 1) t),
    'topIps',    (select coalesce(jsonb_agg(row_to_json(t)), '[]'::jsonb)
                  from (select host(ip) as ip, count(*) n, max(occurred_at) as last_seen
                        from scoped where action <> 'allow' and ip is not null
                        group by 1 order by n desc limit 10) t),
    'topAgents', (select coalesce(jsonb_agg(row_to_json(t)), '[]'::jsonb)
                  from (select user_agent, count(*) n from scoped
                        where action <> 'allow' group by 1 order by n desc limit 10) t),
    'timeline',  (select coalesce(jsonb_agg(row_to_json(t) order by t.bucket), '[]'::jsonb)
                  from (select date_trunc('hour', occurred_at) as bucket,
                               count(*) filter (where action = 'allow')     as allowed,
                               count(*) filter (where action = 'challenge') as challenged,
                               count(*) filter (where action = 'block')     as blocked
                        from scoped group by 1) t)
  );
$$;

